import React from 'react';
import ReactDOM from 'react-dom/client';
import {QueryClient,QueryClientProvider} from '@tanstack/react-query';
import {BrowserRouter} from 'react-router-dom';
import {SessionProvider} from './lib/session';
import App from './App';
import './styles.css';
import './foundation.css';
const queryClient=new QueryClient({defaultOptions:{queries:{retry:1,staleTime:2000},mutations:{retry:false,networkMode:'always'}}});
ReactDOM.createRoot(document.getElementById('root')!).render(<React.StrictMode><QueryClientProvider client={queryClient}><BrowserRouter><SessionProvider><App/></SessionProvider></BrowserRouter></QueryClientProvider></React.StrictMode>);
if(import.meta.env.PROD&&'serviceWorker' in navigator)window.addEventListener('load',()=>{void navigator.serviceWorker.register('/sw.js').catch(()=>{/* Installability status is shown in settings; API remains network-only. */})});
